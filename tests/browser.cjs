const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'test-results');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const executablePath = process.env.BROWSER_PATH || [
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  ].find(p => fs.existsSync(p));
  const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [], externalRequests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => { if (/^https?:/.test(r.url())) externalRequests.push(r.url()); });
    await page.goto(pathToFileURL(path.join(root, 'demo.html')).href);
    await page.waitForSelector('#timeline button');
    assert.equal(await page.locator('#counter').textContent(), '0 / 4');
    assert.equal(await page.locator('#diagram [data-node]').count(), 4);
    await page.locator('#next').click();
    assert.equal(await page.locator('#counter').textContent(), '1 / 4');
    assert.equal(await page.locator('[data-edge="e1"]').getAttribute('stroke'), '#c6f27c');
    await page.locator('#prev').click();
    assert.equal(await page.locator('#counter').textContent(), '0 / 4');
    await page.locator('#play').click();
    await page.waitForTimeout(120);
    const x1 = await page.locator('circle[aria-hidden]').getAttribute('cx');
    await page.waitForTimeout(120);
    assert.notEqual(await page.locator('circle[aria-hidden]').getAttribute('cx'), x1);
    await page.locator('#play').click();
    assert.equal(await page.locator('#play').textContent(), '▶ Play');
    const pausedCounter = await page.locator('#counter').textContent();
    await page.waitForTimeout(250);
    assert.equal(await page.locator('#counter').textContent(), pausedCounter);
    await page.locator('#scenario').selectOption('1');
    assert.equal(await page.locator('#counter').textContent(), '0 / 6');
    await page.locator('#timeline button').nth(3).click();
    assert.equal(await page.locator('[data-edge="e4"]').getAttribute('stroke'), '#c6f27c');
    assert.equal(await page.locator('#timeline button[aria-current="step"]').count(), 1);
    await page.screenshot({ path: path.join(output, 'cache-desktop.png'), fullPage: true });
    await page.locator('#scrub').fill('6');
    assert.equal(await page.locator('#counter').textContent(), '6 / 6');
    await page.locator('#speed').selectOption('2');
    await page.locator('#play').click();
    await page.waitForTimeout(150);
    await page.locator('#play').click();
    await page.locator('#play').click();
    assert.equal(await page.locator('#counter').textContent(), '6 / 6', 'Resuming final step must not restart');
    await page.waitForFunction(() => document.getElementById('play').textContent.includes('Replay'));
    await page.locator('#play').click();
    assert.equal(await page.locator('#counter').textContent(), '1 / 6');
    await page.locator('#reset').click();
    assert.equal(await page.locator('#counter').textContent(), '0 / 6');
    await page.locator('h1').click();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#counter').textContent(), '1 / 6');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const svgPath = path.join(output, 'snapshot.svg');
    await download.saveAs(svgPath);
    assert.ok(fs.readFileSync(svgPath, 'utf8').includes('marker-end'));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'cache-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Page should not overflow horizontally');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('#play').click();
    assert.equal(await page.locator('circle[aria-hidden]').getAttribute('visibility'), 'hidden');
    await page.locator('#reset').click();
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.goto(pathToFileURL(path.join(root, 'sequence-demo.html')).href);
    await page.locator('#timeline button').nth(2).click();
    assert.equal(await page.locator('[data-edge="e3"]').getAttribute('stroke'), '#c6f27c');
    const selfPath = await page.locator('[data-edge="e3"]').getAttribute('d');
    assert.ok(selfPath.includes('v 34'), 'Self message should loop back to its participant');
    const returnPath = await page.locator('[data-edge="e5"]').getAttribute('d');
    const numbers = returnPath.match(/[\d.]+/g).map(Number);
    assert.ok(numbers[0] > numbers[2], 'Response points back toward client');
    await page.screenshot({ path: path.join(output, 'sequence-desktop.png'), fullPage: true });
    assert.deepEqual(errors, [], 'Browser errors');
    assert.deepEqual(externalRequests, [], 'Viewer must be offline');
    console.log('PASS: flowchart, scenarios, particle motion, pause/resume, steps, replay, reset, keyboard, export, mobile, reduced motion, sequence direction, zero network requests.');
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
